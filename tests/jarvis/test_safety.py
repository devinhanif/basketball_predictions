"""Structural guarantees: read-only, no execution code, no credentials, no writes outside JARVIS's
own book. These grep/AST the package so a future edit cannot quietly break them."""

from __future__ import annotations

import ast
import json
import re
from pathlib import Path

import yaml

PKG = Path("nba/jarvis")
FILES = sorted(PKG.glob("*.py"))


def source() -> str:
    return "\n".join(p.read_text() for p in FILES)


def test_no_order_portfolio_or_signing_endpoint_anywhere() -> None:
    src = source().lower()
    for word in (
        "/orders", "create_order", "place_order", "portfolio", "/trade-api/v2/portfolio",
        "clob.polymarket", "private_key", "api_key", "apikey", "authorization", "bearer ",
        "kalshi-access", "signature", "wallet", "submit_order", "cancel_order",
    ):  # fmt: skip
        assert word not in src, word


def test_network_is_get_only_and_confined_to_one_module() -> None:
    for p in FILES:
        tree = ast.parse(p.read_text())
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute) and node.attr in ("post", "put", "patch", "delete"):
                base = ast.unparse(node.value)
                assert not any(h in base for h in ("http", "client", "session", "requests")), (
                    p,
                    base,
                )
    imports = {
        p.name
        for p in FILES
        if re.search(r"^\s*(import|from) (httpx|requests|urllib|socket)", p.read_text(), re.M)
    }
    assert imports <= {"polymarket.py"}, imports


def test_osascript_only_in_imessage_and_never_through_a_shell() -> None:
    users = [p.name for p in FILES if "osascript" in p.read_text()]
    assert users == ["imessage.py"]
    assert "shell=True" not in source() and "os.system" not in source()


def test_nba_duckdb_is_only_opened_read_only() -> None:
    for p in FILES:
        for node in ast.walk(ast.parse(p.read_text())):
            if isinstance(node, ast.Call) and ast.unparse(node.func) == "duckdb.connect":
                kw = {k.arg: ast.unparse(k.value) for k in node.keywords}
                if p.name == "book.py" and "_con" in ast.unparse(node):
                    continue
                if p.name == "book.py":
                    # the one writable store is JARVIS's own paper book (self.path)
                    assert ast.unparse(node.args[0]) == "str(self.path)", ast.unparse(node)
                    continue
                assert kw.get("read_only") == "True", (p.name, ast.unparse(node))


def test_season_2025_is_not_referenced() -> None:
    src = source()
    assert not re.search(r"season\s*(=|==|IN|in)\s*\(?\s*2025", src)
    assert "season = 2026" in src


def test_config_names_the_env_var_but_holds_no_secret() -> None:
    cfg = yaml.safe_load(Path("configs/jarvis.yaml").read_text())
    assert cfg["delivery"]["env_var"] == "JARVIS_IMESSAGE_TO"
    blob = json.dumps(cfg).lower()
    for w in ("password", "token", "secret", "api_key", "key:"):
        assert w not in blob, w


def test_no_ai_attribution_in_the_package() -> None:
    src = (source() + Path("configs/jarvis.yaml").read_text()).lower()
    for w in ("co-authored", "generated by", "claude", "anthropic"):
        assert w not in src, w


def test_the_play_is_never_given_up() -> None:
    """The only place 'keep your money' may appear is a refusal/blocklist, never an answer."""
    for p in FILES:
        for m in re.finditer(r"keep your money", p.read_text(), re.I):
            line = p.read_text()[: m.start()].count("\n")
            ctx = "\n".join(p.read_text().splitlines()[max(0, line - 3) : line + 2]).lower()
            assert any(
                k in ctx for k in ("never", "refus", "_giveup", "_give", "re.compile", "reject")
            ), (p.name, ctx)


def test_launchd_template_is_valid_uses_uv_and_holds_no_recipient() -> None:
    import plistlib

    from nba.jarvis.imessage import recipient_from_env

    d = plistlib.loads(Path("ops/launchd/local.nba.jarvis.plist").read_bytes())
    assert d["Label"] == "local.nba.jarvis" and d["RunAtLoad"] is False
    assert d["ProgramArguments"][0].endswith("/uv")
    assert d["ProgramArguments"][-2:] == ["watch", "--once"]
    assert "/bin/sh" not in d["ProgramArguments"]
    placeholder = d["EnvironmentVariables"]["JARVIS_IMESSAGE_TO"]
    assert recipient_from_env("JARVIS_IMESSAGE_TO", {"JARVIS_IMESSAGE_TO": placeholder}) is None
