"""Assemble the ALIGNED 2023-2025 rows that ``fit_gate.py`` consumes (AVG_SHADOW_LIVE_2, "What the steward builds" 3; HOLDOUT_ACCESS_LOG rows 72, 73, 76).

Season-2025 use here is TRAINING / SYSTEMS only: the rows are A0 forecasts, the rebuild's E2 forecasts and the labels the T442 gate is fit on. This script never scores a
forecast, never computes a loss, a CRPS or a contrast, and prints only row counts, season counts and equality booleans. It is the one place season-2025 forecasts sit
next to labels on the Mac, so it is deliberately small:

1. the stored A0/FULL world (seasons <= 2024) and the rebuild's E2 forecasts for those seasons (as ``_world.py``);
2. season 2025's A0 members regenerated by T478's own ``forecast_members`` under the raised cap (same code path as ``seq_full_mix_eval._body``), after gate B: the same
   regeneration of 2024 under that cap must equal the stored arrays (integer grids, exactly), else STOP;
3. the real-tip covariates of 2025 from the REBUILD's export meta; the rebuild's 2025 E2 forecasts from ``oof_E2.npz``;
4. one npz: per stat a0_199, seq_199, y, the five context columns, date_days, season.

    PYTHONPATH=<repo> .venv/bin/python -W ignore research/colab/jobs/avg_shadow_rebuild/gate_rows.py --run <run folder> --out <dir>/gate_rows.npz
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

import numpy as np

STATS = ("pts", "reb", "ast", "fg3m")
TARGET = 2025
REBUILD_META = "data/colab/avg_shadow_rebuild/seq_ensemble_rt_cur25_meta.parquet"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    ap.add_argument("--run", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument(
        "--meta", type=Path, required=True, help="the rebuild's seq_ensemble_rt_cur25_meta.parquet"
    )
    ap.add_argument(
        "--root",
        type=Path,
        required=True,
        help="the repo whose data/ and nba.duckdb are read (relative paths in the research loaders)",
    )
    a = ap.parse_args(argv)
    os.chdir(a.root)  # the loaders resolve data/ and nba.duckdb relative to the working directory
    from research.eval import recent_role_full_eval as F
    from research.eval import seq_full_mix_eval as S
    from research.eval import workload_eval as WE
    from research.eval.recent_role_holdout import preimport, season_cap

    S.configure_rt(
        None, None
    )  # SEQ_FULL_MIX_RT bindings (real-tip covariates for the stored 2023/24 rows)
    preimport()
    report: dict[str, object] = {"target": TARGET}
    with WE.heavy():
        w = S.stored_world_base()
        assert int(max(w["base"][st]["season"].max() for st in STATS)) <= 2024
        with season_cap(TARGET):
            fr, cfg, _ = F.build_frame()
            F.assert_cap(TARGET)
            # gate B: the raised cap must not move the stored seasons
            tests = S.members_vs_stored(
                S.forecast_members(fr, cfg, 2024), w, 2024, "gate B, cap 2025"
            )
            report["gate_B_2024"] = [{"test": t["test"][:60], "ok": t["ok"]} for t in tests]
            if not all(t["ok"] for t in tests):
                a.out.parent.mkdir(parents=True, exist_ok=True)
                (a.out.parent / "gate_rows_STOP.json").write_text(
                    json.dumps(report, indent=1, default=str)
                )
                print(json.dumps(report, indent=1, default=str))
                return 1
            members = S.forecast_members(fr, cfg, TARGET)
            del fr
            tgt, tgt_days = S.target_base(members, a.meta)
        world = S.combine_world(w, tgt, tgt_days, TARGET)
        S.attach_seq(world, a.run, ("E2",), TARGET)
        seq = world["seq_programs"]["E2"]
        base = world["base"]
        ref = base["pts"]
        z: dict[str, np.ndarray] = {}
        for st in STATS:
            b = base[st]
            assert np.array_equal(b["game_id"], ref["game_id"]) and np.array_equal(
                b["player_id"], ref["player_id"]
            ), st
            z[f"{st}_a0_199"] = np.asarray(b["mix"], dtype=np.float64)
            z[f"{st}_seq_199"] = np.asarray(seq[st], dtype=np.float64)
            z[f"{st}_y"] = np.asarray(b["y"], dtype=np.float64)
            z[f"{st}_n_prior"] = np.asarray(ref["n_prior"], dtype=np.float64)
            for c in ("starter10", "n_rep_out", "has_report", "team_game_no"):
                z[f"{st}_{c}"] = np.asarray(ref[c], dtype=np.float64)
            z[f"{st}_date_days"] = np.asarray(world["date_days"]).astype(np.int64)
            z[f"{st}_season"] = np.asarray(ref["season"]).astype(np.int64)
        seasons, counts = np.unique(ref["season"], return_counts=True)
        report["rows_by_season"] = {int(s): int(c) for s, c in zip(seasons, counts, strict=True)}
        report["n_rows"] = int(len(ref["season"]))
        report["date_min"] = str(np.min(np.asarray(world["date_days"]).astype("datetime64[D]")))
        report["date_max"] = str(np.max(np.asarray(world["date_days"]).astype("datetime64[D]")))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    np.savez(a.out, **z)  # type: ignore[arg-type]
    (a.out.parent / "gate_rows_report.json").write_text(json.dumps(report, indent=1, default=str))
    print(json.dumps(report, indent=1, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
