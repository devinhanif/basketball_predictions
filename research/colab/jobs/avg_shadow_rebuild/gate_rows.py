"""Assemble the ALIGNED 2023-2025 rows that ``fit_gate.py`` consumes (AVG_SHADOW_LIVE_2, "What the steward builds" 3; HOLDOUT_ACCESS_LOG rows 72, 73, 76).

Season-2025 use here is TRAINING / SYSTEMS only: the rows are A0 forecasts, the rebuild's E2 forecasts and the labels the T442 gate is fit on. This script never scores a
forecast, never computes a loss, a CRPS or a contrast, and prints only row counts, season counts and equality booleans. It is the one place season-2025 forecasts sit
next to labels on the Mac, so it is deliberately small:

1. the stored A0/FULL world (seasons <= 2024) and the rebuild's E2 forecasts for those seasons (as ``_world.py``);
2. season 2025's A0 members regenerated by T478's own ``forecast_members`` under the raised cap (same code path as ``seq_full_mix_eval._body``), after gate B: the same
   regeneration of 2024 under that cap must equal the stored arrays (integer grids, exactly), else STOP;
3. the real-tip covariates of 2025 from the REBUILD's export meta; the rebuild's 2025 E2 forecasts from ``oof_E2.npz``;
4. one npz: per stat a0_199, seq_199, y, the five context columns, date_days, season, and (since the S1 fix, 2026-10-14 review) game_id / player_id.

Row order (review S1, docs/reviews/AVG_SHADOW_LIVE_2_gate_rows_2026-10-14.md). The A0 row order (game_id, player_id as the stored world and T478's
``forecast_members`` emit it, date-monotone) is the one order; every key join in the loaders is a left join whose output is consumed by position, and polars
documents ``maintain_order="none"`` as its default (the order may differ between versions or runs). ``ordered_joins`` pins every ``DataFrame.join`` in this
run to ``maintain_order="left"`` (an ordering pin: same keys, same matches, same row set), and ``verify_alignment`` then re-derives every aligned field BY
KEY with a dict (not a join) from the OOF file and the meta, and fails the run on any mismatch or duplicate key. The frozen procedure (members, covariates,
gate inputs) is unchanged: only the order is made explicit and checked.

    PYTHONPATH=<repo> .venv/bin/python -W ignore research/colab/jobs/avg_shadow_rebuild/gate_rows.py --run <run folder> --out <dir>/gate_rows.npz
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import Any

import numpy as np

STATS = ("pts", "reb", "ast", "fg3m")
TARGET = 2025
# starter10 is not checked: it comes from the A0 members (not a meta join) and the review found it exact for 2023/24
CONTEXT_COLUMNS = ("n_prior", "team_game_no", "has_report", "n_rep_out")


@contextmanager
def ordered_joins() -> Iterator[None]:
    """Pin ``polars.DataFrame.join`` to ``maintain_order="left"`` unless the caller says otherwise (S1). Restored on exit, even on error."""
    import polars as pl

    orig = pl.DataFrame.join

    def joined(self: Any, *args: Any, **kw: Any) -> Any:
        if (
            kw.get("how", "inner") in ("left", "inner", "right", "full")
            and "maintain_order" not in kw
        ):
            kw["maintain_order"] = "left"
        return orig(self, *args, **kw)

    pl.DataFrame.join = joined  # type: ignore[method-assign]
    try:
        yield
    finally:
        pl.DataFrame.join = orig  # type: ignore[method-assign]


def key_index(game_id: np.ndarray, player_id: np.ndarray, what: str) -> dict[tuple[str, int], int]:
    """(game_id, player_id) -> row, by a dict; a duplicate key is an error (a join on it would expand or reorder rows)."""
    idx: dict[tuple[str, int], int] = {}
    for i, k in enumerate(
        zip(game_id.astype(str).tolist(), player_id.astype(np.int64).tolist(), strict=True)
    ):
        if k in idx:
            raise RuntimeError(f"{what}: duplicate key {k}")
        idx[k] = i
    return idx


def positions(
    idx: dict[tuple[str, int], int], game_id: np.ndarray, player_id: np.ndarray, what: str
) -> np.ndarray:
    """The row of every (game_id, player_id) in ``idx``; a missing key is an error."""
    keys = zip(game_id.astype(str).tolist(), player_id.astype(np.int64).tolist(), strict=True)
    try:
        return np.fromiter((idx[k] for k in keys), dtype=np.int64, count=len(game_id))
    except KeyError as e:
        raise RuntimeError(f"{what}: key {e.args[0]} missing") from e


def verify_alignment(
    z: dict[str, np.ndarray],
    stats: tuple[str, ...],
    oof: dict[str, np.ndarray],
    meta: dict[str, np.ndarray],
    ext19: Callable[[np.ndarray], np.ndarray],
) -> dict[str, int]:
    """Dict-based (no polars) proof that every row of the assembled arrays is the right row: per stat, ``seq_199`` equals ``ext19(oof q)`` at the row's own key,
    the context columns and ``date_days`` equal the meta's at the row's own key, the stat arrays share one key order, and no key repeats. Raises on any difference."""
    ref = stats[0]
    gid, pid = z[f"{ref}_game_id"], z[f"{ref}_player_id"]
    n = len(gid)
    oi = positions(key_index(oof["game_id"], oof["player_id"], "oof"), gid, pid, "oof")
    mi = positions(key_index(meta["game_id"], meta["player_id"], "meta"), gid, pid, "meta")
    key_index(gid, pid, "assembled rows")
    dd = meta["date_days"][mi].astype(np.int64)
    for si, st in enumerate(stats):
        if not (
            np.array_equal(z[f"{st}_game_id"], gid) and np.array_equal(z[f"{st}_player_id"], pid)
        ):
            raise RuntimeError(f"{st}: rows are not in {ref}'s key order")
        if not np.array_equal(z[f"{st}_seq_199"], ext19(oof["q"][oi, si, :])):
            raise RuntimeError(f"{st}: seq_199 differs from the OOF forecast of the row's own key")
        for c in CONTEXT_COLUMNS:
            if not np.array_equal(z[f"{st}_{c}"], np.asarray(meta[c][mi], dtype=np.float64)):
                raise RuntimeError(f"{st}: {c} differs from the meta at the row's own key")
        if not np.array_equal(z[f"{st}_date_days"], dd):
            raise RuntimeError(f"{st}: date_days differs from the meta at the row's own key")
    return {"rows": n, "stats": len(stats)}


def file_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    ap.add_argument("--run", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument(
        "--meta", type=Path, required=True, help="the rebuild's seq_ensemble_rt_cur25_meta.parquet"
    )
    ap.add_argument(
        "--root",
        type=Path,
        required=True,
        help="the repo whose data/ and nba.duckdb are read (relative paths in the research loaders)",
    )
    a = ap.parse_args(argv)
    os.chdir(a.root)  # the loaders resolve data/ and nba.duckdb relative to the working directory
    import pandas as pd

    from research.eval import ensemble_eval as E
    from research.eval import recent_role_full_eval as F
    from research.eval import seq_full_mix_eval as S
    from research.eval import workload_eval as WE
    from research.eval.recent_role_holdout import preimport, season_cap

    S.configure_rt(
        None, None
    )  # SEQ_FULL_MIX_RT bindings (real-tip covariates for the stored 2023/24 rows)
    preimport()
    report: dict[str, object] = {"target": TARGET}
    with WE.heavy(), ordered_joins():
        w = S.stored_world_base()
        assert int(max(w["base"][st]["season"].max() for st in STATS)) <= 2024
        with season_cap(TARGET):
            fr, cfg, _ = F.build_frame()
            F.assert_cap(TARGET)
            # gate B: the raised cap must not move the stored seasons
            tests = S.members_vs_stored(
                S.forecast_members(fr, cfg, 2024), w, 2024, "gate B, cap 2025"
            )
            report["gate_B_2024"] = [{"test": t["test"][:60], "ok": t["ok"]} for t in tests]
            if not all(t["ok"] for t in tests):
                a.out.parent.mkdir(parents=True, exist_ok=True)
                (a.out.parent / "gate_rows_STOP.json").write_text(
                    json.dumps(report, indent=1, default=str)
                )
                print(json.dumps(report, indent=1, default=str))
                return 1
            members = S.forecast_members(fr, cfg, TARGET)
            del fr
            tgt, tgt_days = S.target_base(members, a.meta)
        world = S.combine_world(w, tgt, tgt_days, TARGET)
        S.attach_seq(world, a.run, ("E2",), TARGET)
        seq = world["seq_programs"]["E2"]
        base = world["base"]
        ref = base["pts"]
        z: dict[str, np.ndarray] = {}
        for st in STATS:
            b = base[st]
            assert np.array_equal(b["game_id"], ref["game_id"]) and np.array_equal(
                b["player_id"], ref["player_id"]
            ), st
            z[f"{st}_game_id"] = np.asarray(ref["game_id"]).astype(str)
            z[f"{st}_player_id"] = np.asarray(ref["player_id"]).astype(np.int64)
            z[f"{st}_a0_199"] = np.asarray(b["mix"], dtype=np.float64)
            z[f"{st}_seq_199"] = np.asarray(seq[st], dtype=np.float64)
            z[f"{st}_y"] = np.asarray(b["y"], dtype=np.float64)
            z[f"{st}_n_prior"] = np.asarray(ref["n_prior"], dtype=np.float64)
            for c in ("starter10", "n_rep_out", "has_report", "team_game_no"):
                z[f"{st}_{c}"] = np.asarray(ref[c], dtype=np.float64)
            z[f"{st}_date_days"] = np.asarray(world["date_days"]).astype(np.int64)
            z[f"{st}_season"] = np.asarray(ref["season"]).astype(np.int64)
        oofz = np.load(a.run / "oof_E2.npz", allow_pickle=True)
        oof = {k: oofz[k] for k in ("game_id", "player_id", "q")}
        oof["game_id"], oof["player_id"] = (
            oof["game_id"].astype(str),
            oof["player_id"].astype(np.int64),
        )
        mp = pd.read_parquet(a.meta)
        meta = {c: mp[c].to_numpy() for c in ("game_id", "player_id", *CONTEXT_COLUMNS)}
        meta["game_id"] = meta["game_id"].astype(str)
        meta["date_days"] = mp["game_date"].to_numpy().astype("datetime64[D]").astype(np.int64)
        report["alignment_by_key"] = verify_alignment(z, STATS, oof, meta, E.ext19)
        report["inputs"] = {
            "run": str(a.run),
            "oof_E2_sha256": file_sha256(a.run / "oof_E2.npz"),
            "meta_sha256": file_sha256(a.meta),
        }
        seasons, counts = np.unique(ref["season"], return_counts=True)
        report["rows_by_season"] = {int(s): int(c) for s, c in zip(seasons, counts, strict=True)}
        report["n_rows"] = int(len(ref["season"]))
        report["date_min"] = str(np.min(np.asarray(world["date_days"]).astype("datetime64[D]")))
        report["date_max"] = str(np.max(np.asarray(world["date_days"]).astype("datetime64[D]")))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    np.savez(a.out, **z)  # type: ignore[arg-type]
    report["npz_sha256"] = file_sha256(a.out)
    (a.out.parent / "gate_rows_report.json").write_text(json.dumps(report, indent=1, default=str))
    print(json.dumps(report, indent=1, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
